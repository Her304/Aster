export const bloomTranslations: Readonly<Record<Locale, BloomTable>> = { en, "zh-Hant": zhHant, ja, ko };

function interpolate(template: string, variables?: TranslationVariables) {
  if (!variables) return template;
  return template.replace(/\{\{\s*([\w.-]+)\s*\}\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(variables, key) ? String(variables[key]) : match,
  );
}

export function bloomText(locale: Locale, key: BloomKey, variables?: TranslationVariables) {
  return interpolate(bloomTranslations[locale][key] ?? en[key], variables);
}

export function useBloomCopy() {
  const { locale } = useI18n();
  return useCallback((key: BloomKey, variables?: TranslationVariables) => bloomText(locale, key, variables), [locale]);
}

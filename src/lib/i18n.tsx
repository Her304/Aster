function englishQuestion(text: string, name: string, self: boolean) {
  if (!self) return text.replaceAll("{{name}}", name);

  const statement = text.replace(/^\{\{name\}\}\s+/, "");
  const match = statement.match(/^([A-Za-z]+)(.*)$/s);
  if (!match) return text.replaceAll("{{name}}", "I");

  const [, verb, rest] = match;
  return `I ${englishFirstPersonVerbs[verb] ?? verb}${rest}`;
}

export function translateQuestion(
  questionId: number,
  fallbackEnglish: string,
  name: string,
  self: boolean,
  locale: Locale,
): string {
  if (locale === "en") return englishQuestion(fallbackEnglish, name, self);

  const table = questionTranslations[locale];
  const template = table[questionId as SurveyQuestionId];
  if (!template) return englishQuestion(fallbackEnglish, name, self);

  const subject = self
    ? locale === "zh-Hant"
      ? "我"
      : locale === "ja"
        ? "私は"
        : "저는 "
    : locale === "zh-Hant"
      ? name
      : locale === "ja"
        ? `${name}さんは`
        : `${name}님은 `;

  return template.replaceAll("{{subject}}", subject);
}

export type TranslationVariables = Readonly<Record<string, string | number>>;

function interpolate(template: string, variables?: TranslationVariables) {
  if (!variables) return template;
  return template.replace(/\{\{\s*([\w.-]+)\s*\}\}/g, (token, key: string) =>
    Object.prototype.hasOwnProperty.call(variables, key) ? String(variables[key]) : token,
  );
}

export interface I18nContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: TranslationKey, variables?: TranslationVariables) => string;
  locales: typeof localeOptions;
  localeLabels: typeof localeLabels;
}

const I18nContext = createContext<I18nContextValue | null>(null);
const STORAGE_KEY = "aster_locale";

function isLocale(value: string | null | undefined): value is Locale {
  return value === "en" || value === "zh-Hant" || value === "ja" || value === "ko";
}

function browserLocale(): Locale {
  if (typeof navigator === "undefined") return "en";
  const language = navigator.language.toLowerCase();
  if (language.startsWith("zh")) return "zh-Hant";
  if (language.startsWith("ja")) return "ja";
  if (language.startsWith("ko")) return "ko";
  return "en";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("en");

  useEffect(() => {
    let next = browserLocale();
    try {
      const stored = window.localStorage.getItem(STORAGE_KEY);
      if (isLocale(stored)) next = stored;
    } catch {
      // Storage can be unavailable in privacy-restricted browsing contexts.
    }
    setLocaleState(next);
    document.documentElement.lang = next;
  }, []);

  const setLocale = useCallback((next: Locale) => {
    setLocaleState(next);
    document.documentElement.lang = next;
    try {
      window.localStorage.setItem(STORAGE_KEY, next);
    } catch {
      // The selected language still applies for the current page session.
    }
  }, []);

  const t = useCallback(
    (key: TranslationKey, variables?: TranslationVariables) =>
      interpolate(translations[locale][key] ?? translations.en[key], variables),
    [locale],
  );

  const value = useMemo<I18nContextValue>(
    () => ({ locale, setLocale, t, locales: localeOptions, localeLabels }),
    [locale, setLocale, t],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used within an I18nProvider");
  return value;
}
